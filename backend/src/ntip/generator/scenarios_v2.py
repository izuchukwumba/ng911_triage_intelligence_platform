"""Scenario families for generator 2.0 (ML layer design, section 4.3).

Generator 1.0 had 17 families with 3 phrasings each, and six cue codes never
appeared in a training family. Generator 2.0 has 66 families with 3 to 6
phrasings each (279 in all, plus denials, past-tense and Spanish versions),
covers all 32 labelled cue codes, and puts every code in at
least one training family (dev or regression) and one test family, so a
model can be trained on a code and tested on unseen phrasings of it.

Phrasings mark the evidence for each cue: ``[CODE|exact words]``. The
generator renders the text, keeps the marks as character spans through every
perturbation, and records them as label schema 2.0 cue annotations. A
phrasing must express, and mark exactly once, every cue of its family; a test
enforces this.

Severities follow the labelling guide (v2.1), not the triage engine. Labels
are generator-intended (design v1.2, section 12.3), not verified ground truth.
"""

