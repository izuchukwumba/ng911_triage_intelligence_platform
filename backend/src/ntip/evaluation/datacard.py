"""Dataset cards (ML layer design, sections 4 and 9).

Each dataset in ``data/eval`` has a card in ``data/eval/cards`` with the same
stem. The prose (motivation, how it was made, intended and unsuitable uses,
limitations) is written by hand. The composition section between the
``stats`` markers is generated from the data, so it cannot drift:

    python -m ntip.evaluation.datacard            # rewrite the generated sections
    python -m ntip.evaluation.datacard --check    # exit 1 if any is out of date
"""

import argparse
from collections import Counter
from pathlib import Path

from ntip.evaluation.dataset import Dataset, EvalCase, LabelSource, Split, load_dataset

BEGIN = "<!-- stats:begin (generated by python -m ntip.evaluation.datacard; do not edit) -->"
END = "<!-- stats:end -->"
SPLITS = [s.value for s in Split]


def _row(label: str, counts: dict[str, int], total: bool = True) -> str:
    cells = [str(counts.get(s, 0)) for s in SPLITS]
    if total:
        cells.append(str(sum(counts.values())))
    return f"| {label} | " + " | ".join(cells) + " |"


def statistics(dataset: Dataset) -> str:
    by_split: dict[str, list[EvalCase]] = {s: dataset.split(Split(s)) for s in SPLITS}
    header = "| | " + " | ".join(SPLITS) + " | all |"
    rule = "|---" * (len(SPLITS) + 2) + "|"
    lines = [
        f"Dataset `{dataset.path}` · digest `{dataset.digest}`",
        "",
        header,
        rule,
        _row("Cases", {s: len(c) for s, c in by_split.items()}),
        _row("Families", {s: len({x.family for x in c}) for s, c in by_split.items()}),
        _row(
            "Cases with evidence spans",
            {
                s: sum(1 for x in c if x.labels.cue_annotations is not None)
                for s, c in by_split.items()
            },
        ),
        _row(
            "Multi-message cases",
            {s: sum(1 for x in c if len(x.messages) > 1) for s, c in by_split.items()},
        ),
    ]
    sources = Counter(c.label_source.value for c in dataset.cases)
    lines += ["", "Label source: " + ", ".join(f"{k} {v}" for k, v in sorted(sources.items()))]

    def table(title: str, key: str, values: dict[str, Counter[str]]) -> list[str]:
        names = sorted({k for counter in values.values() for k in counter})
        if not names:
            return []
        out = ["", f"### {title}", "", f"| {key} | " + " | ".join(SPLITS) + " | all |", rule]
        for name in names:
            out.append(_row(f"`{name}`", {s: values[s][name] for s in SPLITS}))
        return out

    lines += table(
        "Priority",
        "Priority",
        {s: Counter(x.labels.priority for x in c) for s, c in by_split.items()},
    )
    lines += table(
        "Domain",
        "Domain",
        {s: Counter(x.labels.domain for x in c) for s, c in by_split.items()},
    )
    lines += table(
        "Live cues (cases reporting each)",
        "Cue",
        {s: Counter(code for x in c for code in x.labels.cues) for s, c in by_split.items()},
    )
    lines += table(
        "Denied, past or hypothetical cues",
        "Cue",
        {s: Counter(code for x in c for code in x.labels.absent_cues) for s, c in by_split.items()},
    )
    variants = {
        s: Counter(
            v
            for x in c
            # Only generated cases list their variants in the notes; author notes are prose.
            if x.label_source is LabelSource.GENERATOR and "; " in x.notes
            for v in x.notes.split("; ", 1)[1].split(", ")
        )
        for s, c in by_split.items()
    }
    lines += table("Variants (from case notes)", "Variant", variants)
    return "\n".join(lines)


def render(card: str, dataset: Dataset) -> str:
    """The card with its generated section replaced."""
    if BEGIN not in card or END not in card:
        raise ValueError("card has no stats markers")
    head, rest = card.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{statistics(dataset)}\n{END}{tail}"


def cards(data_dir: Path) -> list[tuple[Path, Path]]:
    """(dataset, card) for every dataset; a dataset without a card is an error."""
    pairs = []
    for dataset in sorted(data_dir.glob("*.jsonl")):
        card = data_dir / "cards" / f"{dataset.stem}.md"
        if not card.exists():
            raise FileNotFoundError(f"{dataset.name} has no card ({card.name})")
        pairs.append((dataset, card))
    return pairs


def main(argv: list[str] | None = None) -> int:
    from ntip.evaluation.runner import REPO_ROOT

    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for dataset_path, card_path in cards(REPO_ROOT / "data" / "eval"):
        current = card_path.read_text("utf-8").replace("\r\n", "\n")
        updated = render(current, load_dataset(dataset_path))
        if current != updated:
            stale.append(card_path.name)
            if not args.check:
                card_path.write_text(updated, encoding="utf-8", newline="\n")
    if args.check:
        print("stale: " + ", ".join(stale) if stale else "up to date")
        return 1 if stale else 0
    print("updated: " + ", ".join(stale) if stale else "up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
