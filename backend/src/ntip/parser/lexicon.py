"""Phrase lists used by the rules parser.

Ported from the TypeScript parser (services/transcript-parser/src/keywords.ts)
with these deliberate changes:

- Observation codes describe what was *reported*, not a diagnosis.
- Cues that combined unrelated conditions ("immediate_medical_emergency") are
  split into specific codes; triage decides how they combine.
- Phrases that only worked because of substring matching, or that biased the
  domain vote ("help me" counted as EMS), are removed.
- New cues the design calls for: fire/smoke reported, occupants trapped, and
  the caller not knowing their location.

Matching is word-bounded (see ``ntip.parser.text``), so each phrase must be a
whole word or word sequence.
"""

